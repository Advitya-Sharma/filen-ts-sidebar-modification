// Generates the SpreadsheetML child-order table (src/core/xlsx/write/order.generated.ts by default): the child
// order of the containers an xlsx writer splices into and the enumerations it validates against, from the
// Transitional sml.xsd of ECMA-376 Part 4 (5th edition), the archive generate:wml-order fetches and pins.
// Each schema the SpreadsheetML set adds is checked against its own pin.
//
//   tsx src/scripts/smlOrder.ts [--out <file>] [<ECMA-376-4 zip | OfficeOpenXML-XMLSchema-Transitional.zip>]
//
// Without an archive argument the Part 4 archive is read from the generate:wml-order cache, or downloaded.

export const OUTPUT = fileURLToPath(new URL("../core/xlsx/write/order.generated.ts", import.meta.url))

