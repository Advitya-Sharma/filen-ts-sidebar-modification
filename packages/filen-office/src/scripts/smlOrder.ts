function sha256(bytes: Uint8Array): string {
	return createHash("sha256").update(bytes).digest("hex")
}

// The pinned SpreadsheetML schemas from the Transitional set, each checked against SML_SCHEMAS.
export function smlSchemas(files: ReadonlyMap<string, Uint8Array>): Map<string, Uint8Array> {
	const out = new Map<string, Uint8Array>()

	for (const [name, digest] of Object.entries(SML_SCHEMAS)) {
		const bytes = files.get(name)

		if (bytes === undefined) throw new Error(`${name} is missing from the schema set`)
		if (sha256(bytes) !== digest) throw new Error(`${name} does not match its pinned SHA-256`)

		out.set(name, bytes)
	}

	return out
}

export async function renderOrder(schema: Uint8Array, output = OUTPUT): Promise<string> {
	const document = parseXml(schema)
	const source = [
		"// Generated by `tsx src/scripts/smlOrder.ts` from ECMA-376 Part 4 (5th edition) sml.xsd",
		`// (SHA-256 ${SML_SCHEMAS["sml.xsd"]}), © Ecma International, see THIRD_PARTY_NOTICES.md.`,
		"// Do not edit. Child element local names in schema order, then enumerated values.",
		"",
		...Object.entries(CONTAINERS).map(
			([name, type]) => `// ${type}\nexport const ${name}: readonly string[] = ${JSON.stringify(elementOrder(document, type))}\n`
		),
		...Object.entries(ENUMERATIONS).map(
			([name, type]) =>
				`// ${type}\nexport const ${name}: ReadonlySet<string> = new Set(${JSON.stringify(enumeration(document, type))})\n`
		)
	].join("\n")

	return format(source, { ...(await resolveConfig(OUTPUT)), filepath: output })
}

async function main(): Promise<void> {
	const args = process.argv.slice(2)
	const outIndex = args.indexOf("--out")
	const output = outIndex >= 0 ? (args[outIndex + 1] ?? OUTPUT) : OUTPUT
	const archive = args.find((_, index) => outIndex < 0 || (index !== outIndex && index !== outIndex + 1))
	const bytes = archive !== undefined ? new Uint8Array(readFileSync(archive)) : await cachedArchive()
	const schema = smlSchemas(transitionalSchemas(bytes)).get("sml.xsd") as Uint8Array

	mkdirSync(dirname(output), { recursive: true })
	writeFileSync(output, await renderOrder(schema, output))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
