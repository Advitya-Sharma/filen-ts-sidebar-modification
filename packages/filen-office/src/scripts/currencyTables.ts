import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { format, resolveConfig } from "prettier"

// Generates src/core/sheet/input/currencies.generated.ts, each territory's currency, from the Unicode CLDR
// supplemental data pinned below (version and SHA-256): supplementalData.xml <currencyData>, the first currency of
// each <region> that is legal tender now (no "to" date, not tender="false"; CLDR lists a region's currencies in
// order of preference). The download goes to a cache under node_modules.
//
//   pnpm exec tsx src/scripts/currencyTables.ts

export const CLDR_VERSION = "49"

const URL_ = `https://raw.githubusercontent.com/unicode-org/cldr/release-${CLDR_VERSION}/common/supplemental/supplementalData.xml`
const SHA256 = "745150ec1408d50e1a272b65654a5dd645f3e60f5cc2898b576f725b28538d1a"

const CACHE = fileURLToPath(new URL(`../../node_modules/.cache/filen-office-cldr/${CLDR_VERSION}/`, import.meta.url))
const OUTPUT = fileURLToPath(new URL("../core/sheet/input/currencies.generated.ts", import.meta.url))

function sha256(bytes: Uint8Array): string {
	return createHash("sha256").update(bytes).digest("hex")
}

async function supplementalData(): Promise<string> {
	const path = `${CACHE}supplementalData.xml`

	if (!existsSync(path)) {
		const response = await fetch(URL_)

		if (!response.ok) throw new Error(`supplementalData.xml: HTTP ${response.status}`)

		mkdirSync(CACHE, { recursive: true })
		writeFileSync(path, new Uint8Array(await response.arrayBuffer()))
	}

	const bytes = new Uint8Array(readFileSync(path))

	if (sha256(bytes) !== SHA256) throw new Error("supplementalData.xml does not match its pinned SHA-256")

	return new TextDecoder().decode(bytes)
}

// Territory (ISO 3166-1 alpha-2, or CLDR's two-letter macro codes such as EU) → its current ISO 4217 currency.
export function currentCurrencies(xml: string): Map<string, string> {
	const start = xml.indexOf("<currencyData>")
	const end = xml.indexOf("</currencyData>", start)

	if (start < 0 || end < 0) throw new Error("no <currencyData>")

	const data = xml.slice(start, end)
	const table = new Map<string, string>()

	for (const region of data.matchAll(/<region iso3166="([A-Z]{2})">([\s\S]*?)<\/region>/g)) {
		const [, territory = "", body = ""] = region

		for (const currency of body.matchAll(/<currency\s([^>]*?)\/>/g)) {
			const attributes = currency[1] ?? ""
			const code = /iso4217="([A-Z]{3})"/.exec(attributes)?.[1]

			if (code === undefined || /(^|\s)to="/.test(attributes) || /tender="false"/.test(attributes)) continue

			table.set(territory, code)
			break
		}
	}

	return table
}

async function main(): Promise<void> {
	const table = currentCurrencies(await supplementalData())
	const packed = [...table].sort(([a], [z]) => (a < z ? -1 : 1)).map(([territory, code]) => territory + code)

	const source = `// Generated by src/scripts/currencyTables.ts from Unicode CLDR ${CLDR_VERSION} (common/supplemental/supplementalData.xml,
// ${URL_}). Do not edit.

export const CLDR_VERSION = "${CLDR_VERSION}"

// Each territory's current currency: five letters each, the territory's two (sorted) and its ISO 4217 code.
export const TERRITORY_CURRENCIES = "${packed.join("")}"
`

	writeFileSync(OUTPUT, await format(source, { ...(await resolveConfig(OUTPUT)), filepath: OUTPUT }))
	console.log(`territories ${table.size}, ${packed.join("").length} characters`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
