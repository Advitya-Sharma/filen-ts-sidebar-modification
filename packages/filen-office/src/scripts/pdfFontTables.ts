import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { format, resolveConfig } from "prettier"

// Generates src/core/pdfwrite/fonts/faces.generated.ts from assets/fonts/manifest.json: the gzip'd TrueType
// faces each bundled family has for PDF embedding, and the Noto fallback families by script.
//
//   pnpm exec tsx src/scripts/pdfFontTables.ts

const MANIFEST = fileURLToPath(new URL("../../assets/fonts/manifest.json", import.meta.url))
const OUTPUT = fileURLToPath(new URL("../core/pdfwrite/fonts/faces.generated.ts", import.meta.url))

interface Face {
	readonly file: string
	readonly weight: number
	readonly italic: boolean
	readonly bytes: number
	readonly ttf: { readonly bytes: number }
}

interface Manifest {
	readonly families: readonly { readonly id: string; readonly pdf?: readonly Face[] }[]
	readonly fallbacks: readonly { readonly id: string; readonly scripts: readonly string[]; readonly faces: readonly Face[] }[]
}

function row(face: Face): string {
	return `{ file: ${JSON.stringify(face.file)}, weight: ${face.weight}, italic: ${face.italic}, bytes: ${face.bytes}, ttfBytes: ${face.ttf.bytes} }`
}

async function main(): Promise<void> {
	const manifest = JSON.parse(readFileSync(MANIFEST, "utf8")) as Manifest
	const families = manifest.families.map(family => {
		if (family.pdf === undefined || family.pdf.length === 0) throw new Error(`${family.id} has no PDF faces`)

		return `${family.id}: [${family.pdf.map(row).join(", ")}]`
	})
	const fallbacks = manifest.fallbacks.map(
		family =>
			`{ id: ${JSON.stringify(family.id)}, scripts: ${JSON.stringify(family.scripts)}, faces: [${family.faces.map(row).join(", ")}] }`
	)
	const source = `// Generated by src/scripts/pdfFontTables.ts from assets/fonts/manifest.json. Do not edit.

import type { BundledFamily } from "../../fonts/substitutes"

// A gzip'd TrueType face under assets/fonts: bytes as stored, ttfBytes once decompressed.
export interface PdfFaceFile {
	readonly file: string
	readonly weight: number
	readonly italic: boolean
	readonly bytes: number
	readonly ttfBytes: number
}

export interface FallbackFamily {
	readonly id: string
	// ISO 15924 codes the family is the fallback for, preferred first.
	readonly scripts: readonly string[]
	readonly faces: readonly PdfFaceFile[]
}

export const PDF_FACES: Readonly<Record<BundledFamily, readonly PdfFaceFile[]>> = { ${families.join(",\n")} }

export const FALLBACK_FAMILIES: readonly FallbackFamily[] = [${fallbacks.join(",\n")}]
`

	writeFileSync(OUTPUT, await format(source, { ...(await resolveConfig(OUTPUT)), filepath: OUTPUT }))
	console.log(`${families.length} families, ${fallbacks.length} fallbacks`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
