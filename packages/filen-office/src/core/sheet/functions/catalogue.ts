export type ArgumentId = keyof typeof ARGUMENT_LABELS

const PREFIXES: readonly FunctionPrefix[] = ["_xlfn._xlws.", "_xlfn."]

function split(stored: string): { prefix: FunctionPrefix; name: string } {
	const prefix = PREFIXES.find(candidate => stored.startsWith(candidate)) ?? ""

	return { prefix, name: stored.slice(prefix.length) }
}

function isArgumentId(id: string): id is ArgumentId {
	return Object.hasOwn(ARGUMENT_LABELS, id)
}

function parseArguments(signature: string, name: string): FunctionArgument[] {
	const args: FunctionArgument[] = []
	// The optional group being read, until its closing bracket.
	let group: ArgumentId[] | null = null

	for (const token of signature.split(" ")) {
		if (token === "") {
			continue
		}

		const repeats = token.endsWith("...")
		const body = repeats ? token.slice(0, -3) : token
		const opens = body.startsWith("[")
		const closes = body.endsWith("]")
		const id = body.slice(opens ? 1 : 0, closes ? -1 : undefined)

		if (!isArgumentId(id)) {
			throw new Error(`function catalogue: ${name} has an unlabelled argument ${id}`)
		}

		if (opens) {
			group = []
		}

		if (group === null) {
			args.push({ id, optional: false, repeats })

			continue
		}

		group.push(id)

		if (closes) {
			for (const member of group) {
				args.push({ id: member, optional: true, repeats })
			}

			group = null
		}
	}

	return args
}

// The most arguments a signature allows: each once, or with a repeating group, as many copies of the group as
// fit within Excel's limit.
function widest(args: readonly FunctionArgument[]): number {
	const size = args.filter(arg => arg.repeats).length

	if (size === 0) {
		return args.length
	}

	const fixed = args.length - size

	return fixed + size * Math.floor((MAX_FUNCTION_ARGUMENTS - fixed) / size)
}

function build([stored, category, signature, support, extra]: Row): SheetFunction {
	const { prefix, name } = split(stored)
	const args = parseArguments(signature, name)

	return {
		name,
		prefix,
		category,
		args,
		minArgs: extra?.min ?? args.filter(arg => !arg.optional).length,
		maxArgs: extra?.max ?? widest(args),
		volatility: extra?.volatility ?? "none",
		support
	}
}

interface Catalogue {
	readonly list: readonly SheetFunction[]
	readonly byName: ReadonlyMap<string, SheetFunction>
}

let catalogue: Catalogue | null = null

function load(): Catalogue {
	if (catalogue === null) {
		const list = ROWS.map(build)

		catalogue = { list, byName: new Map(list.map(entry => [entry.name, entry])) }
	}

	return catalogue
}

// Every function, in alphabetical order. Built on first use.
export function sheetFunctions(): readonly SheetFunction[] {
	return load().list
}

// A function by its name as typed ("stdev.s") or as a file stores it ("_xlfn.STDEV.S").
export function sheetFunction(name: string): SheetFunction | undefined {
	return load().byName.get(split(name.toUpperCase().replace(/^_XLFN\.(_XLWS\.)?/u, "_xlfn.")).name)
}
