// Excel's worksheet functions: the 521 names on Microsoft's "Excel functions (alphabetical)"
// (support.microsoft.com), each with its arguments and arity, category, volatility, the prefix a file stores it
// under and how this app calculates it. Data only, for autocomplete, signature help and the coverage tests.
//
// - Arguments: each function's syntax on its own page there (for FIND and the byte variants LEFTB, LENB, MIDB,
//   REPLACEB, RIGHTB, SEARCHB and FINDB, whose pages are retired, the Excel JavaScript API reference,
//   Excel.Functions, on learn.microsoft.com). A function that takes a function argument (LAMBDA's helpers) has it
//   as `function`. An id is the argument's name there in lower case; the numbering of an argument that repeats is
//   dropped ("number1, [number2], ..." is `number [number]...`), other numbered names are distinct arguments.
//   Ids are stable: they key ARGUMENT_LABELS, our own short wording, and later the labels' translations.
// - Arity: what the syntax allows, up to Excel's 255 arguments per function ("Excel specifications and limits").
//   A future function that repeats stops where the [MS-XLSX] 2.2.2 grammar stops it (254 or 253), and REDUCE and
//   SCAN take three there: their optional first argument still holds its place.
// - Prefix: the [MS-XLSX] 2.2.3 future functions are stored as "_xlfn.NAME" ("_xlfn._xlws." for FILTER and SORT).
//   Functions newer than that list, or missing from it and from the built-in table of [MS-XLSB] 2.5.98.10 (Ftab),
//   are stored as "_xlfn." too.
// - Volatility: "always" for those learn.microsoft.com's "Excel Recalculation" names volatile, and RAND and
//   RANDARRAY, which return new numbers at every calculation (their pages); "arguments" for INFO, CELL and SUMIF,
//   volatile depending on their arguments there.
// - Support: "hyperformula" for the names HyperFormula 3.4.0 registers; "cached" for those that need a network
//   service, an add-in, an OLAP connection or a locale's character tables, whose result in the file is kept;
//   "plugin" for the rest, to be added to the engine.

export type FunctionCategory =
	| "addIn"
	| "compatibility"
	| "cube"
	| "database"
	| "dateTime"
	| "engineering"
	| "financial"
	| "information"
	| "logical"
	| "lookup"
	| "math"
	| "statistical"
	| "text"
	| "web"

export type FunctionSupport = "hyperformula" | "plugin" | "cached"

export type FunctionPrefix = "" | "_xlfn." | "_xlfn._xlws."

export type FunctionVolatility = "none" | "always" | "arguments"

export interface FunctionArgument {
	readonly id: ArgumentId
	readonly optional: boolean
	// Part of the trailing group that may be given again (up to maxArgs).
	readonly repeats: boolean
}

export interface SheetFunction {
	// As typed and shown: "STDEV.S".
	readonly name: string
	// What a file stores before the name: "_xlfn.STDEV.S".
	readonly prefix: FunctionPrefix
	readonly category: FunctionCategory
	readonly args: readonly FunctionArgument[]
	readonly minArgs: number
	readonly maxArgs: number
	readonly volatility: FunctionVolatility
	readonly support: FunctionSupport
}

// Excel's limit on the arguments of one function call.
export const MAX_FUNCTION_ARGUMENTS = 255

